    /// <summary>프롤로그 나레이션 + 방 장면 데이터를 런타임에 만듭니다.</summary>
    public static PrologueDialogueData CreatePrologueRuntime()
    {
        var data = ScriptableObject.CreateInstance<PrologueDialogueData>();
        data.narrationLines = BuildPrologueNarration();
        data.roomLines = BuildPrologueRoom();
        return data;
    }

    /// <summary>스테이지 번호에 맞는 Open/Close 대사를 런타임에 만듭니다.</summary>
    public static StageDialogueData CreateStageRuntime(int stageNumber)
    {
        var data = ScriptableObject.CreateInstance<StageDialogueData>();
        data.stageNumber = stageNumber;

        switch (stageNumber)
        {
            case 1:
                data.openLines = BuildStage01Open();
                data.closeLines = BuildStage01Close();
                break;
            case 2:
                data.openLines = BuildStage02Open();
                data.closeLines = BuildStage02Close();
                break;
            case 3:
                data.openLines = BuildStage03Open();
                data.closeLines = BuildStage03Close();
                break;
            case 4:
                data.openLines = BuildStage04Open();
                data.closeLines = BuildStage04Close();
                break;
            case 5:
                data.openLines = BuildStage05Open();
                data.closeLines = BuildStage05Close();
                break;
            case 6:
                data.openLines = BuildStage06Open();
                data.closeLines = BuildStage06Close();
                break;
            case 7:
                data.openLines = BuildStage07Open();
                data.closeLines = BuildStage07Close();
                break;
            case 8:
                data.openLines = BuildStage08Open();
                data.closeLines = BuildStage08Close();
                break;
            case 9:
                data.openLines = BuildStage09Open();
                data.closeLines = BuildStage09Close();
                break;
            case 10:
                data.openLines = BuildStage10Open();
                data.closeLines = BuildStage10Close();
                break;
            default:
                data.openLines = new List<DialogueLine>
                {
                    Line("주인공", $"[임시] 스테이지 {stageNumber} 오프닝 대사입니다.")
                };
                data.closeLines = new List<DialogueLine>
                {
                    Line("주인공", $"[임시] 스테이지 {stageNumber} 클리어 대사입니다.", "happy")
                };
                break;
        }

        return data;
    }

    /// <param name="expression">비우면 이전 표정 유지. 예: default, wake, nervous, dark, angry, cry, sparkle, scheming, happy</param>
    public static DialogueLine Line(string speaker, string text, string expression = "", string eventId = "")
    {
        return new DialogueLine
        {
            speakerName = speaker,
            dialogueText = text,
            expressionId = expression,
            characterPosition = CharacterPosition.Center,
            eventId = eventId
        };
    }

    public static DialogueLine EventOnly(string eventId)
    {
        return new DialogueLine
        {
            speakerName = "",
            dialogueText = "",
            expressionId = "",
            eventId = eventId
        };
    }

